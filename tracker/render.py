"""LEADERBOARD.md, data/latest.json and the README excerpt, from history entries."""

from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Mapping, Optional, Sequence, Tuple

from .history import Entry, Row

API_GUIDE_URL = "https://spotify.checkleaked.cc/spotify-monthly-listeners-api"
ARTIST_URL = "https://open.spotify.com/artist/{}"
README_START = "<!-- leaderboard:start -->"
README_END = "<!-- leaderboard:end -->"
NOTICE = "Unofficial. The numbers are what Spotify shows on public artist pages; not affiliated with Spotify."
NONE = "—"

# ASCII punctuation that could change how a name renders inside a table link
# ("$" opens math on GitHub, "|" ends the cell, "[" "]" break the link).
_MARKDOWN_SPECIAL = re.compile(r"([\\`*_\[\]<>|$~])")


def escape_markdown(text: str) -> str:
    return _MARKDOWN_SPECIAL.sub(r"\\\1", " ".join(text.split()))


def artist_link(row: Row) -> str:
    name = escape_markdown(row.name) or row.artist_id
    return f"[{name}]({ARTIST_URL.format(row.artist_id)})"


def format_count(value: Optional[int]) -> str:
    return NONE if value is None else f"{value:,}"


def format_change(difference: Optional[int], percent: Optional[float]) -> str:
    if difference is None:
        return NONE
    text = "0" if difference == 0 else f"{difference:+,}"
    if percent is not None:
        text += " (0.00%)" if difference == 0 else f" ({percent:+.2f}%)"
    return text


def rank_entries(entries: Sequence[Entry]) -> List[Entry]:
    """Most monthly listeners first; artists without a value last; ties by followers, then name."""

    return sorted(
        entries,
        key=lambda e: (
            e.row.monthly_listeners is None,
            -(e.row.monthly_listeners or 0),
            -(e.row.followers or 0),
            e.row.name.casefold(),
            e.row.artist_id,
        ),
    )


def _movers(entries: Sequence[Entry], limit: int) -> Tuple[Optional[int], List[Entry], List[Entry]]:
    """``(days, biggest gains, biggest drops)`` over 7 days, else 1 day, else nothing."""

    for days, attribute in ((7, "change_7d"), (1, "change_1d")):
        changed = [e for e in entries if getattr(e, attribute) is not None]
        if changed:
            gains = sorted((e for e in changed if getattr(e, attribute) > 0), key=lambda e: -getattr(e, attribute))
            drops = sorted((e for e in changed if getattr(e, attribute) < 0), key=lambda e: getattr(e, attribute))
            return days, gains[:limit], drops[:limit]
    return None, [], []


def render_leaderboard(
    entries: Sequence[Entry],
    *,
    day: str,
    tracked: int,
    top: int = 100,
    not_updated: int = 0,
    movers: int = 10,
) -> str:
    """The LEADERBOARD.md text."""

    ranked = rank_entries(entries)
    shown = ranked[:top]
    lines = [
        "# Spotify monthly listeners leaderboard",
        "",
        f"The {len(shown)} artists with the most Spotify monthly listeners on **{day}** (UTC), "
        f"out of the {tracked} artists in [`artists.txt`](artists.txt). Updated once a day.",
        "",
        "Changes compare an artist's monthly listeners with the same artist's value 1 and 7 days "
        f"earlier; {NONE} means there is no earlier value yet. World rank is Spotify's own global "
        f"rank, which Spotify shows only for its most-listened artists ({NONE} for the others).",
        "",
        "<!-- Generated by `python -m tracker` from data/history.csv. Manual edits are overwritten by the next run. -->",
        "",
        "| # | Artist | Monthly listeners | 1-day change | 7-day change | Followers | World rank |",
        "|--:|:--|--:|--:|--:|--:|--:|",
    ]
    for position, entry in enumerate(shown, start=1):
        row = entry.row
        lines.append(
            f"| {position} | {artist_link(row)} | {format_count(row.monthly_listeners)} "
            f"| {format_change(entry.change_1d, entry.change_1d_pct)} "
            f"| {format_change(entry.change_7d, entry.change_7d_pct)} "
            f"| {format_count(row.followers)} | {format_count(row.world_rank)} |"
        )
    days, gains, drops = _movers(ranked, movers)
    if days is not None:
        span = "7 days" if days == 7 else "1 day"
        attribute = "change_7d" if days == 7 else "change_1d"
        for title, group in ((f"Most listeners gained in {span}", gains), (f"Most listeners lost in {span}", drops)):
            if not group:
                continue
            lines += ["", f"## {title}", "", f"Among all {tracked} tracked artists.", ""]
            lines += ["| # | Artist | Change | Monthly listeners |", "|--:|:--|--:|--:|"]
            for position, entry in enumerate(group, start=1):
                difference = getattr(entry, attribute)
                percent = getattr(entry, attribute + "_pct")
                lines.append(
                    f"| {position} | {artist_link(entry.row)} | {format_change(difference, percent)} "
                    f"| {format_count(entry.row.monthly_listeners)} |"
                )
    lines += [
        "",
        "## Data",
        "",
        "- [`data/history.csv`](data/history.csv): one row per artist per day since tracking started.",
        "- [`data/latest.json`](data/latest.json): this day's values for every tracked artist, with changes and top cities.",
    ]
    if not_updated:
        lines += [
            "",
            f"{not_updated} tracked artist(s) have no value for {day}: the API could not fetch them in "
            "this run. Their earlier values are in data/history.csv.",
        ]
    lines += [
        "",
        f"Collected with the [Spotify monthly listeners API]({API_GUIDE_URL}). {NOTICE}",
        "",
    ]
    return "\n".join(lines)


def _percent(value: Optional[float]) -> Optional[float]:
    return None if value is None else round(value, 4)


def build_latest(
    entries: Sequence[Entry],
    *,
    day: str,
    tracked: int,
    cities: Optional[Mapping[str, List[Dict[str, Any]]]] = None,
    not_updated: Sequence[Tuple[str, Optional[Row]]] = (),
) -> Dict[str, Any]:
    """The data/latest.json document (deterministic: no timestamps beyond the date)."""

    cities = cities or {}
    artists = []
    for position, entry in enumerate(rank_entries(entries), start=1):
        row = entry.row
        artists.append(
            {
                "position": position,
                "id": row.artist_id,
                "name": row.name,
                "monthly_listeners": row.monthly_listeners,
                "followers": row.followers,
                "world_rank": row.world_rank,
                "change_1d": entry.change_1d,
                "change_1d_pct": _percent(entry.change_1d_pct),
                "change_7d": entry.change_7d,
                "change_7d_pct": _percent(entry.change_7d_pct),
                "url": ARTIST_URL.format(row.artist_id),
                "top_cities": list(cities.get(row.artist_id, [])),
            }
        )
    return {
        "date": day,
        "tracked_artists": tracked,
        "artists_with_data": len(artists),
        "source": API_GUIDE_URL,
        "notice": NOTICE,
        "artists": artists,
        "not_updated": [
            {"id": artist_id, "name": last.name if last else None, "last_date": last.date if last else None}
            for artist_id, last in not_updated
        ],
    }


def dump_latest(document: Mapping[str, Any]) -> str:
    """JSON text with one artist per line, so a day's diff reads artist by artist."""

    keys = list(document)
    lines = ["{"]
    for index, key in enumerate(keys):
        value = document[key]
        comma = "," if index < len(keys) - 1 else ""
        if isinstance(value, list) and value and all(isinstance(item, dict) for item in value):
            lines.append(f"  {json.dumps(key)}: [")
            for item_index, item in enumerate(value):
                item_comma = "," if item_index < len(value) - 1 else ""
                lines.append("    " + json.dumps(item, ensure_ascii=False) + item_comma)
            lines.append("  ]" + comma)
        else:
            lines.append(f"  {json.dumps(key)}: {json.dumps(value, ensure_ascii=False)}{comma}")
    lines.append("}")
    return "\n".join(lines) + "\n"


def cities_from_latest(text: str, day: str) -> Dict[str, List[Dict[str, Any]]]:
    """Top cities stored in an earlier latest.json for the same day (else nothing)."""

    try:
        document = json.loads(text)
    except ValueError:
        return {}
    if not isinstance(document, dict) or document.get("date") != day:
        return {}
    out = {}
    for artist in document.get("artists") or []:
        if isinstance(artist, dict) and isinstance(artist.get("id"), str) and isinstance(artist.get("top_cities"), list):
            out[artist["id"]] = artist["top_cities"]
    return out


def render_excerpt(entries: Sequence[Entry], *, day: str, top: int = 10) -> str:
    """The short table that goes between the README markers."""

    shown = rank_entries(entries)[:top]
    lines = [
        f"Top {len(shown)} of the tracked artists on **{day}** (UTC). "
        "Full top 100 with 1-day changes: [LEADERBOARD.md](LEADERBOARD.md).",
        "",
        "| # | Artist | Monthly listeners | 7-day change |",
        "|--:|:--|--:|--:|",
    ]
    for position, entry in enumerate(shown, start=1):
        lines.append(
            f"| {position} | {artist_link(entry.row)} | {format_count(entry.row.monthly_listeners)} "
            f"| {format_change(entry.change_7d, entry.change_7d_pct)} |"
        )
    return "\n".join(lines)


def replace_section(text: str, content: str) -> str:
    """``text`` with ``content`` between the README markers (unchanged when they are missing)."""

    start = text.find(README_START)
    end = text.find(README_END, start + len(README_START)) if start != -1 else -1
    if start == -1 or end == -1:
        return text
    return text[: start + len(README_START)] + "\n" + content.strip("\n") + "\n" + text[end:]
